#define FONT_N ((int)(sizeof(FONT)/sizeof(FONT[0])))

static const Glyph *find_glyph(char c)
{
	int i;
	if (c >= 'a' && c <= 'z')
		c -= 32; /* font is uppercase only */
	for (i = 0; i < FONT_N; i++)
		if (FONT[i].ch == c)
			return &FONT[i];
	return NULL;
}

float text_width(const char *str, float scale)
{
	int n = 0;
	if (scale < 1.0f) scale = 1.0f;
	while (*str++) n++;
	return (float)n * 6.0f * scale;
}

void text_draw(const char *str, float x, float y, float scale, u32 color)
{
	int i;
	if (scale < 1.0f) scale = 1.0f;
	while (*str) {
		const Glyph *g = find_glyph(*str);
		if (g) {
			for (i = 0; i < 7; i++) {
				unsigned char row = g->r[i];
				int b;
				for (b = 0; b < 5; b++) {
					if (row & (1 << (4 - b)))
						gfx_rect(x + (float)b * scale,
						         y + (float)i * scale,
						         scale, scale, color);
				}
			}
		}
		x += 6.0f * scale;
		str++;
	}
}

void text_draw_center(const char *str, float cx, float y, float scale, u32 color)
{
	text_draw(str, cx - text_width(str, scale) * 0.5f, y, scale, color);
}

void text_draw_shadow(const char *str, float x, float y, float scale, u32 color, u32 shadow)
{
	text_draw(str, x + scale, y + scale, scale, shadow);
	text_draw(str, x, y, scale, color);
}
